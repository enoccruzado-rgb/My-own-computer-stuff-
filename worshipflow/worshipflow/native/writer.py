"""Write a :class:`SongPlan` as a native ProPresenter presentation (.pro).

Structure produced (matches files written by ProPresenter itself):

    Presentation
      cue_groups[]  -> one per song section, holding that section's slide UUIDs
      cues[]        -> one per slide; actions[0] is a presentation-slide action
      arrangements[]-> ordered group UUIDs (repeats allowed)
      selected_arrangement
"""
from __future__ import annotations

import copy
import uuid as uuidlib
from typing import Optional

from ..models import SectionKind, SongPlan
from . import rtf as rtfmod
from .rvproto import action_pb2, applicationInfo_pb2, presentation_pb2, slide_pb2
from .theme import SlideStyle, builtin_style

# Default app version stamped into files: the newest proto set we compile from.
APP_MAJOR, APP_MINOR, APP_BUILD = 21, 4, "352583705"

GROUP_COLORS = {
    SectionKind.VERSE: (0.0, 0.467, 0.8),
    SectionKind.PRE_CHORUS: (0.55, 0.27, 0.8),
    SectionKind.CHORUS: (0.8, 0.0, 0.306),
    SectionKind.POST_CHORUS: (0.8, 0.3, 0.45),
    SectionKind.BRIDGE: (0.6, 0.4, 0.0),
    SectionKind.TAG: (0.2, 0.6, 0.3),
    SectionKind.VAMP: (0.2, 0.6, 0.3),
    SectionKind.REFRAIN: (0.8, 0.0, 0.306),
    SectionKind.INTRO: (0.4, 0.4, 0.4),
    SectionKind.OUTRO: (0.4, 0.4, 0.4),
    SectionKind.ENDING: (0.6, 0.56, 0.12),
    SectionKind.INSTRUMENTAL: (0.3, 0.3, 0.3),
    SectionKind.INTERLUDE: (0.3, 0.3, 0.3),
    SectionKind.BLANK: (0.15, 0.15, 0.15),
    SectionKind.OTHER: (0.5, 0.5, 0.5),
}


class UuidSource:
    """Random UUIDs by default; deterministic (seeded) for reproducible tests."""

    def __init__(self, seed: Optional[str] = None):
        self.seed = seed
        self.n = 0

    def __call__(self) -> str:
        self.n += 1
        if self.seed is None:
            return str(uuidlib.uuid4()).upper()
        return str(uuidlib.uuid5(uuidlib.NAMESPACE_URL, f"worshipflow:{self.seed}:{self.n}")).upper()


def _new_element(proto: slide_pb2.Slide.Element, text: str, uuids: UuidSource, uppercase: bool) -> slide_pb2.Slide.Element:
    se = copy.deepcopy(proto)
    se.element.uuid.string = uuids()
    se.element.text.rtf_data = rtfmod.retext_rtf(se.element.text.rtf_data, text, uppercase=uppercase)
    return se


def build_presentation(plan: SongPlan, style: Optional[SlideStyle] = None, *, uuid_seed: Optional[str] = None) -> presentation_pb2.Presentation:
    style = style or builtin_style("standard")
    uuids = UuidSource(uuid_seed)
    song = plan.song
    pres = presentation_pb2.Presentation()

    ai = pres.application_info
    ai.platform = applicationInfo_pb2.ApplicationInfo.PLATFORM_MACOS
    ai.application = applicationInfo_pb2.ApplicationInfo.APPLICATION_PROPRESENTER
    ai.platform_version.major_version = 14
    ai.application_version.major_version = APP_MAJOR
    ai.application_version.minor_version = APP_MINOR
    ai.application_version.build = APP_BUILD

    pres.uuid.string = uuids()
    pres.name = song.title
    pres.category = "Song"
    notes = [f"Generated by WorshipFlow from {song.source.kind} lyrics"]
    if song.version.label and song.version.label != "default":
        notes.append(f"Version: {song.version.label}")
    pres.notes = ". ".join(notes)
    pres.background.color.alpha = 1.0
    pres.chord_chart.platform = 1  # PLATFORM_MACOS
    pres.timeline.duration = 300.0

    group_uuid: dict[str, str] = {}
    for sec in song.sections:
        cue_group = pres.cue_groups.add()
        g = cue_group.group
        g.uuid.string = group_uuid.setdefault(sec.name, uuids())
        g.name = sec.name
        r, gg, b = GROUP_COLORS.get(sec.kind, GROUP_COLORS[SectionKind.OTHER])
        g.color.red, g.color.green, g.color.blue, g.color.alpha = r, gg, b, 1.0
        g.hotKey.SetInParent()
        for cue_plan in plan.cues_for(sec.name):
            cue = pres.cues.add()
            cue.uuid.string = uuids()
            cue.hot_key.SetInParent()
            cue.isEnabled = True
            cue.completion_action_type = 1  # COMPLETION_ACTION_TYPE_LAST, as ProPresenter writes it
            action = cue.actions.add()
            action.uuid.string = uuids()
            action.isEnabled = True
            action.type = action_pb2.Action.ACTION_TYPE_PRESENTATION_SLIDE
            ps = action.slide.presentation
            ps.chord_chart.platform = 1
            bs = ps.base_slide
            bs.uuid.string = uuids()
            bs.size.width, bs.size.height = style.slide_size
            # Lowest index renders frontmost: lyrics first, then translation, then decorations.
            if cue_plan.lines:
                bs.elements.append(_new_element(style.text_element, cue_plan.text, uuids, style.uppercase))
                if cue_plan.translation_lines:
                    proto = style.translation_element or style.text_element
                    bs.elements.append(_new_element(proto, "\n".join(cue_plan.translation_lines), uuids, style.uppercase))
            for deco in style.decorations:
                d = copy.deepcopy(deco)
                d.element.uuid.string = uuids()
                bs.elements.append(d)
            cue_group.cue_identifiers.add().string = cue.uuid.string

    arr = pres.arrangements.add()
    arr.uuid.string = uuids()
    arr.name = plan.song.arrangement.name or "Sunday"
    for name in plan.song.arrangement.expanded():
        if name not in group_uuid:
            raise ValueError(f"arrangement step {name!r} has no matching group")
        arr.group_identifiers.add().string = group_uuid[name]
    pres.selected_arrangement.string = arr.uuid.string

    if song.ccli_number or song.authors or song.publisher:
        c = pres.ccli
        c.author = song.authors
        c.artist_credits = song.artist
        c.song_title = song.title
        c.publisher = song.publisher
        if song.copyright_year:
            c.copyright_year = song.copyright_year
        if song.ccli_number:
            c.song_number = song.ccli_number
        c.display = bool(song.ccli_number)
    return pres


def write_pro(plan: SongPlan, path: str, style: Optional[SlideStyle] = None, *, uuid_seed: Optional[str] = None) -> presentation_pb2.Presentation:
    pres = build_presentation(plan, style, uuid_seed=uuid_seed)
    data = pres.SerializeToString()
    with open(path, "wb") as fh:
        fh.write(data)
    return pres
